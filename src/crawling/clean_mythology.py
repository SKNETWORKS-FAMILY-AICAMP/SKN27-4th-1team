def clean_desc(text):
    """마크업 정리"""
    text = re.sub(r'\[br\]', '\n', text)
    text = re.sub(r'\[목차\]|\[clearfix\]|\[각주\]', '', text)
    text = re.sub(r'파일:[^\s\n\|]+', '', text)
    text = re.sub(r'\[\*([^\]]*)\]', r'\1', text)
    text = re.sub(r'~~([^~\n]*)~~', r'\1', text)
    text = re.sub(r'\[\[(?:[^\]|]*\|)?([^\]]+)\]\]', r'\1', text)
    text = re.sub(r'\|\|[^\n]*', '', text)
    text = re.sub(r'^\s*[\|}{]+\s*$', '', text, flags=re.M)
    text = re.sub(r'\{\{[^}]*\}\}', '', text)
    text = re.sub(r'width=\d+[^\s\n]*', '', text)
    text = re.sub(r'height=\d+[^\s\n]*', '', text)
    text = re.sub(r'http[s]?://\S+', '', text)
    text = re.sub(r'</?\w+[^>]*>', '', text)
    text = re.sub(r'--[^-\n]+--', '', text)
    text = re.sub(r'분류:[^\n]+', '', text)
    text = re.sub(r'\[\*[^\]]*\]', '', text)
    text = re.sub(r'\n{3,}', '\n\n', text)
    text = re.sub(r'[ \t]{2,}', ' ', text)
    return text.strip()

def is_fiction(name, desc):
    """게임/애니 캐릭터 감지"""
    # 스탯 형식
    if re.search(r'키\s*:\s*\d+cm|몸무게\s*:\s*\d+kg|생일\s*:\s*\d+월\s*\d+일', desc[:300]):
        return True
    return False

with open(PATH, encoding='utf-8') as f:
    data = json.load(f)

result = []
removed = 0
fixed_origin = 0

for d in data:
    name = d['name']
    desc = d['description']

    # 제거
    if name in REMOVE:
        removed += 1
        continue

    # 캐릭터 스탯 감지
    if is_fiction(name, desc):
        removed += 1
        continue

    # 설명 정리
    d['description'] = clean_desc(desc)

    # 너무 짧으면 제거
    if len(d['description']) < 50:
        removed += 1
        continue

    # origin 수정
    if name in ORIGIN_FIX:
        d['origin'] = ORIGIN_FIX[name]
        fixed_origin += 1

    result.append(d)

print(f'원본: {len(data)}건')
print(f'제거: {removed}건')
print(f'origin 수정: {fixed_origin}건')
print(f'최종: {len(result)}건')

with open(PATH, 'w', encoding='utf-8') as f:
    json.dump(result, f, ensure_ascii=False, indent=2)

# 제목 목록 저장
with open('database/data/_myth_titles.txt', 'w', encoding='utf-8') as f:
    for d in result:
        f.write(f'{d["origin"]} | {d["name"]}\n')

