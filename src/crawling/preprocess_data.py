def clean_content(text):
    # [br] → 줄바꿈
    text = re.sub(r'\[br\]', '\n', text)
    # 완전 제거 (내용 없음)
    text = re.sub(r'\[목차\]', '', text)
    text = re.sub(r'\[clearfix\]', '', text)
    text = re.sub(r'\[각주\]', '', text)
    text = re.sub(r'파일:[^\s\n\|]+', '', text)
    # 기호만 제거, 내용 유지
    text = re.sub(r'\[\*([^\]]*)\]', r'\1', text)             # [* 각주내용] → 각주내용
    text = re.sub(r'~~([^~\n]*)~~', r'\1', text)              # ~~취소선~~ → 취소선
    text = re.sub(r'\[\[(?:[^\]|]*\|)?([^\]]+)\]\]', r'\1', text)  # [[링크|표시]] → 표시
    # 표 완전 제거
    text = re.sub(r'\|\|[^\n]*', '', text)
    text = re.sub(r'^\s*[\|}{]+\s*$', '', text, flags=re.M)
    # 기타 마크업 제거
    text = re.sub(r'\{\{[^}]*\}\}', '', text)
    text = re.sub(r'width=\d+[^\s\n]*', '', text)
    text = re.sub(r'height=\d+[^\s\n]*', '', text)
    text = re.sub(r'align=[^\s\n]+', '', text)
    text = re.sub(r'={2,}[^=\n]+=*', '', text)
    text = re.sub(r'\[ruby\([^\)]+\)\]', '', text)
    text = re.sub(r'#[a-fA-F0-9]{6}', '', text)
    text = re.sub(r'http[s]?://\S+', '', text)
    text = re.sub(r'</?\w+[^>]*>', '', text)
    text = re.sub(r'^[ \t]*[-*#]+[ \t]+', '', text, flags=re.M)
    text = re.sub(r'\n{3,}', '\n\n', text)
    text = re.sub(r'[ \t]{2,}', ' ', text)
    # 추가 패턴
    text = re.sub(r'--[^-\n]+--', '', text)          # --취소선--
    text = re.sub(r'분류:[^\n]+', '', text)            # 분류:카테고리
    text = re.sub(r'\[\*[^\]]*\]', '', text)           # [* 각주]
    text = re.sub(r'\n{3,}', '\n\n', text)
    return text.strip()


