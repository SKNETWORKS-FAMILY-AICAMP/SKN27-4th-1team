def is_fiction_content(title, content):
    if title in DIRECT_REMOVE_TITLES:
        return True

    combined = title + ' ' + content[:400]
    c400 = content[:400]

    if any(re.search(p, title) for p in FICTION_TITLE_PATTERNS):
        return True
    if any(kw in combined for kw in GAME_KEYWORDS):
        return True
    if any(kw in combined for kw in ANIME_MANGA_KEYWORDS):
        return True
    if any(kw in combined for kw in DRAMA_KEYWORDS):
        return True
    if any(re.search(p, c400) for p in CONTENT_STRUCTURE_PATTERNS):
        return True
    return False


